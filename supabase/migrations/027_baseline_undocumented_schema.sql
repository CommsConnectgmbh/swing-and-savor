-- ── Helper-Funktion (von challenges_read benötigt) ───────────────────────────

create or replace function can_view_challenge(c_id uuid) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from challenges c
    where c.id = c_id
      and (
        c.visibility = 'public'
        or c.challenger_id = auth.uid()
        or c.opponent_id   = auth.uid()
        or auth.uid() = any(c.challenger_team)
        or auth.uid() = any(c.opponent_team)
        or (c.visibility = 'friends' and (
            are_friends(auth.uid(), c.challenger_id)
            or (c.opponent_id is not null and are_friends(auth.uid(), c.opponent_id))
        ))
      )
  );
$$;

