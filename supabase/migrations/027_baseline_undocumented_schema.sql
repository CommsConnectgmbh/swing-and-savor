drop policy if exists seasons_select_public on seasons;
create policy seasons_select_public on seasons for select using (visibility = 'public' or owner_id = auth.uid());
drop policy if exists seasons_insert_self on seasons;
create policy seasons_insert_self on seasons for insert with check (owner_id = auth.uid());
drop policy if exists seasons_update_owner on seasons;
create policy seasons_update_owner on seasons for update using (owner_id = auth.uid());
drop policy if exists seasons_delete_owner on seasons;
create policy seasons_delete_owner on seasons for delete using (owner_id = auth.uid());

drop policy if exists sponsors_select_any on sponsors;
