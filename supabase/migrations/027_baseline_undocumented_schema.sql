drop policy if exists placements_select_public on sponsor_placements;
create policy placements_select_public on sponsor_placements for select using (exists (
  select 1 from tournaments t where t.id = sponsor_placements.tournament_id
    and (t.visibility = 'public' or t.owner_id = auth.uid())));
drop policy if exists placements_modify_owner on sponsor_placements;
create policy placements_modify_owner on sponsor_placements for all
  using (exists (select 1 from tournaments t where t.id = sponsor_placements.tournament_id and t.owner_id = auth.uid()))
  with check (exists (select 1 from tournaments t where t.id = sponsor_placements.tournament_id and t.owner_id = auth.uid()));
